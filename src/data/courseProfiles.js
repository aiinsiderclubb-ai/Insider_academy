export function applyCourseProfile(course) {
  const profile = COURSE_PROFILES[course?.id]
  if (!profile) return course
  return {
    ...course,
    ...profile,
    description: profile.shortDescription,
    descriptionEn: profile.shortDescriptionEn,
  }
}
