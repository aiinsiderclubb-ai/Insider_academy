export function getCurriculum(courseId) {
  return CURRICULUM[resolveCourseId(courseId)] || null
}

export function buildLessonsFromWeeks(courseId, weeks) {
  const prefix = LESSON_PREFIX[courseId] || courseId.slice(0, 2)
  return weeks.map((w) => {
    const hw = w.homework
    return {
      id: `${prefix}w${w.number}`,
      title: `Неделя ${w.number} — ${w.title}`,
      titleEn: `Week ${w.number} — ${w.titleEn}`,
      duration: '2–3 часа',
      durationEn: '2–3 hours',
      videoUrl: '',
      week: w.number,
      weekGoal: w.goal,
      weekGoalEn: w.goalEn,
      weekOutcome: w.outcome,
      weekOutcomeEn: w.outcomeEn,
      weekSkills: w.skills,
      weekSkillsEn: w.skillsEn,
      hwTasks: hw?.tasks,
      hwTasksEn: hw?.tasksEn,
      hwDeliverables: hw?.deliverables,
      hwDeliverablesEn: hw?.deliverablesEn,
      hwCriteria: hw?.criteria,
      hwCriteriaEn: hw?.criteriaEn,
      hwCapstone: hw?.capstone,
      hwCapstoneTitle: hw?.title,
      hwCapstoneTitleEn: hw?.titleEn,
      hwDefense: hw?.defense,
      hwDefenseEn: hw?.defenseEn,
    }
  })
}

export function enrichCourseWithCurriculum(course) {
  const cur = CURRICULUM[course.id]
  const videoData = getVideoLessons(course.id)
  if (videoData) {
    const weeks = buildWeeksFromVideos(course.id)
    const lessons = buildLessonsFromVideos(course.id) || []
    const count = videoData.meta?.videoCount || lessons.length
    return {
      ...course,
      ...(cur ? {
        courseIdea: cur.idea,
        courseIdeaEn: cur.ideaEn,
        fullDescription: cur.idea,
        fullDescriptionEn: cur.ideaEn,
        forAudience: cur.audience,
        forAudienceEn: cur.audienceEn,
      } : {}),
      finalProject: videoData.meta?.finalResult || cur?.finalResult || course.finalProject,
      finalProjectEn: videoData.meta?.finalResult || cur?.finalResultEn || course.finalProjectEn,
      weeks,
      hasHomework: true,
      duration: cur?.durationRu || `${count} видео`,
      durationEn: cur?.durationEn || `${count} videos`,
      lessons,
      goals: cur?.outcomes?.length ? cur.outcomes : [
        weeks?.[0]?.outcome,
        weeks?.[3]?.outcome,
        videoData.meta?.finalResult,
      ].filter(Boolean),
      goalsEn: cur?.outcomesEn?.length ? cur.outcomesEn : [
        weeks?.[0]?.outcomeEn,
        weeks?.[3]?.outcomeEn,
        videoData.meta?.finalResult,
      ].filter(Boolean),
    }
  }
  if (!cur) return course
  const weeks = mergeHomeworkIntoWeeks(course.id, cur.weeks)
  const lessons = buildLessonsFromWeeks(course.id, weeks)
  return {
    ...course,
    courseIdea: cur.idea,
    courseIdeaEn: cur.ideaEn,
    fullDescription: cur.idea,
    fullDescriptionEn: cur.ideaEn,
    forAudience: cur.audience,
    forAudienceEn: cur.audienceEn,
    finalProject: cur.finalResult,
    finalProjectEn: cur.finalResultEn,
    weeks,
    hasHomework: true,
    duration: cur.durationRu || `${lessons.length} видео`,
    durationEn: cur.durationEn || `${lessons.length} videos`,
    lessons,
    goals: cur.outcomes?.length ? cur.outcomes : [
      cur.weeks[0]?.outcome,
      cur.weeks[3]?.outcome,
      cur.finalResult,
    ].filter(Boolean),
    goalsEn: cur.outcomesEn?.length ? cur.outcomesEn : [
      cur.weeks[0]?.outcomeEn,
      cur.weeks[3]?.outcomeEn,
      cur.finalResultEn,
    ].filter(Boolean),
  }
}

