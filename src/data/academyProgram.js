function daysLessons(prefix, count, titleRu, titleEn) {
  return Array.from({ length: count }, (_, i) => ({
    id: `${prefix}${i + 1}`,
    title: `${titleRu} — день ${i + 1}`,
    titleEn: `${titleEn} — day ${i + 1}`,
    duration: '15–25 мин',
    durationEn: '15–25 min',
    videoUrl: '',
  }))
}

function baseCourse({
  id, slug, title, titleEn, shortDescription, shortDescriptionEn,
  fullDescription, fullDescriptionEn, priceEur, duration, durationEn,
  category, categoryEn, goals, goalsEn, tools, skills, audience, audienceEn,
  finalProject, finalProjectEn, image, lessons, isFreeTrial, level = 'Basic',
  hasHomework = false,
}) {
  return {
    id,
    slug: slug || id,
    title,
    titleEn,
    shortDescription,
    shortDescriptionEn,
    description: shortDescription,
    descriptionEn: shortDescriptionEn,
    fullDescription,
    fullDescriptionEn,
    duration,
    durationEn,
    price: 0,
    priceEur: priceEur ?? 0,
    isFreeTrial: isFreeTrial ?? priceEur === 0,
    image,
    category,
    categoryEn,
    level,
    format: 'async',
    delivery: 'recorded',
    stage: STAGE_BY_COURSE[id],
    tools: tools || [],
    toolsEn: tools || [],
    skills: skills || [],
    skillsEn: skills || [],
    forAudience: audience || [],
    forAudienceEn: audienceEn || [],
    finalProject: finalProject || '',
    finalProjectEn: finalProjectEn || '',
    hasHomework,
    goals: goals || [],
    goalsEn: goalsEn || [],
    lessons,
  }
}

